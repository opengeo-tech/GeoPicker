module.exports = (program, process) => {

  const cmds = program.commands.map(c => c.name())
      , opts = program.options.flatMap(o => [o.short, o.long]).filter(Boolean)
      , words = cmds.concat(opts).join(' ');

  process.stdout.write(`# bash completion for geopicker, generated by "geopicker bash-completion"
_geopicker_completions() {
  local cur prev
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  case "$prev" in
    -d|--dataset|-i|--input-file|-c|--config)
      COMPREPLY=( $(compgen -f -- "$cur") )
      return 0
      ;;
  esac
  if [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "${words}" -- "$cur") )
  else
    COMPREPLY=( $(compgen -f -- "$cur") )
  fi
}
complete -F _geopicker_completions geopicker
`);
}
